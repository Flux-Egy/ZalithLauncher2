package com.movtery.zalithlauncher.security

import java.security.GeneralSecurityException
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Authenticated encryption primitive used for credentials at rest.
 * The returned blob is self-contained: `iv (12 bytes) || ciphertext || GCM tag (16 bytes)`.
 */
interface SecretCipher {
    @Throws(GeneralSecurityException::class)
    fun encrypt(plaintext: ByteArray): ByteArray

    @Throws(GeneralSecurityException::class)
    fun decrypt(blob: ByteArray): ByteArray
}

/**
 * AES-256-GCM over a [SecretKey]. On Android the key lives in AndroidKeyStore
 * (see [AndroidKeystoreCipher]); tests use a software key.
 *
 * With AndroidKeyStore keys, randomized encryption is enforced, so the IV must be
 * generated by the provider during `init(ENCRYPT_MODE, key)` and read back via [Cipher.getIV].
 */
open class AesGcmCipher(private val keyProvider: () -> SecretKey) : SecretCipher {
    override fun encrypt(plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, keyProvider())
        val iv = cipher.iv
        if (iv == null || iv.size != IV_LENGTH) {
            throw GeneralSecurityException("Unexpected GCM IV length: ${iv?.size}")
        }
        val sealed = cipher.doFinal(plaintext)
        return iv + sealed
    }

    override fun decrypt(blob: ByteArray): ByteArray {
        if (blob.size < IV_LENGTH + TAG_LENGTH_BYTES) {
            throw GeneralSecurityException("Encrypted credential is truncated (${blob.size} bytes)")
        }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(
            Cipher.DECRYPT_MODE,
            keyProvider(),
            GCMParameterSpec(TAG_LENGTH_BYTES * 8, blob, 0, IV_LENGTH)
        )
        return cipher.doFinal(blob, IV_LENGTH, blob.size - IV_LENGTH)
    }

    companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_LENGTH = 12
        const val TAG_LENGTH_BYTES = 16
    }
}

/**
 * Encodes credential strings for storage as `zlc1:<base64(iv||ciphertext||tag)>`.
 *
 * Migration-friendly by design:
 * - values without the [PREFIX] are legacy plaintext and are returned as-is
 *   (reported via [Decoded.isLegacyPlaintext] so callers can re-save them encrypted);
 * - placeholder values used by offline/unauthenticated accounts ("", "0", "NULL")
 *   are stored unchanged, since they carry no secret;
 * - if no cipher is available (Keystore unusable) values are stored in plaintext and
 *   [Encoded.isInsecure] is set so the caller can warn the user. Login never breaks.
 *
 * @param cipherProvider returns the cipher, or null if secure storage is unavailable.
 * It is invoked lazily and may be called repeatedly.
 */
class CredentialCodec(private val cipherProvider: () -> SecretCipher?) {

    data class Encoded(val stored: String, val isInsecure: Boolean)

    sealed interface Decoded {
        /** Successfully obtained the plaintext */
        data class Value(val plaintext: String, val isLegacyPlaintext: Boolean) : Decoded

        /** Value was encrypted but could not be decrypted (key lost/invalidated or data corrupted) */
        data class Failed(val cause: Throwable) : Decoded
    }

    fun isPlaceholder(value: String): Boolean = value.trim().lowercase() in PLACEHOLDERS

    fun isEncrypted(stored: String?): Boolean = stored != null && stored.startsWith(PREFIX)

    fun encode(plaintext: String?): Encoded? {
        if (plaintext == null) return null
        if (isPlaceholder(plaintext) || isEncrypted(plaintext)) return Encoded(plaintext, isInsecure = false)

        val cipher = runCatching { cipherProvider() }.getOrNull()
            ?: return Encoded(plaintext, isInsecure = true)

        return try {
            val blob = cipher.encrypt(plaintext.toByteArray(Charsets.UTF_8))
            Encoded(PREFIX + Base64.getEncoder().encodeToString(blob), isInsecure = false)
        } catch (e: GeneralSecurityException) {
            Encoded(plaintext, isInsecure = true)
        } catch (e: RuntimeException) {
            // Keystore implementations on some devices throw unchecked exceptions (e.g. ProviderException)
            Encoded(plaintext, isInsecure = true)
        }
    }

    fun decode(stored: String?): Decoded? {
        if (stored == null) return null
        if (!isEncrypted(stored)) {
            return Decoded.Value(stored, isLegacyPlaintext = !isPlaceholder(stored))
        }
        return try {
            val cipher = cipherProvider()
                ?: return Decoded.Failed(GeneralSecurityException("Secure credential storage is unavailable"))
            val blob = Base64.getDecoder().decode(stored.substring(PREFIX.length))
            Decoded.Value(String(cipher.decrypt(blob), Charsets.UTF_8), isLegacyPlaintext = false)
        } catch (e: GeneralSecurityException) {
            Decoded.Failed(e)
        } catch (e: IllegalArgumentException) {
            Decoded.Failed(e) // malformed base64
        } catch (e: RuntimeException) {
            Decoded.Failed(e)
        }
    }

    companion object {
        const val PREFIX = "zlc1:"
        private val PLACEHOLDERS = setOf("", "0", "null")
    }
}
